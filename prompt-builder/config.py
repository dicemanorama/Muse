def _sorted_unique_tags(values: list[str]) -> list[str]:
    seen = set()
    unique = []
    for value in values:
        safe = value.strip()
        key = safe.casefold()
        if not safe or key in seen:
            continue
        seen.add(key)
        unique.append(safe)
    return sorted(unique, key=str.casefold)


