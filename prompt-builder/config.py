def _expand_tag_options(category: str, values: list[str]) -> list[str]:
    additions = CURATED_TAG_EXPANSIONS.get(category)
    if additions is None:
        raise ValueError(f"Missing curated tag expansion for {category}")
    if len(additions) != len(values):
        raise ValueError(
            f"Curated tag expansion for {category} has {len(additions)} entries; "
            f"expected {len(values)}"
        )
    return _sorted_unique_tags(values + additions)


